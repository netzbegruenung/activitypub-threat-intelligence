# Rendered into the postinst of pubsec-fail2ban, inside the "configure" branch.
# build-deb.sh prepends the shared jail map.

PUBSEC_CONFIG=/etc/pubsec-fail2ban/config.toml

pubsec_toml_escape() {
    printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

pubsec_toml_read() {
    [ -f "$PUBSEC_CONFIG" ] || return 0
    sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*\"\(.*\)\"[[:space:]]*\$/\1/p" \
        "$PUBSEC_CONFIG" | head -n 1 | sed -e 's/\\"/"/g' -e 's/\\\\/\\/g'
}

db_get pubsec-fail2ban/api-url
api_url=$RET
db_get pubsec-fail2ban/push-token
push_token=$RET
db_get pubsec-fail2ban/read-token
read_token=$RET
db_get pubsec-fail2ban/ban-active
ban_active=$RET
db_get pubsec-fail2ban/integrations
integrations=$(printf '%s' "$RET" | tr -d ' ' | tr ',' ' ')

# The tokens are cleared from the debconf database once written, so on a plain
# upgrade the answers are empty. Carry the installed values over, otherwise
# every upgrade would regenerate the configuration without credentials.
[ -n "$push_token" ] || push_token=$(pubsec_toml_read push_token)
[ -n "$read_token" ] || read_token=$(pubsec_toml_read read_token)

install -d -m 0750 -o root -g pubsec-fail2ban /etc/pubsec-fail2ban
install -d -m 0755 -o pubsec-fail2ban -g pubsec-fail2ban /var/log/pubsec-fail2ban

new=$(mktemp)
chmod 0640 "$new"

# Heredocs and printf throughout: the echo of dash expands backslash escapes,
# which would undo the quoting of the token values.
{
    cat <<EOF
# Generated by the pubsec-fail2ban package. Run "dpkg-reconfigure
# pubsec-fail2ban" to change the answers given at install time; hand edits are
# preserved on upgrade.

[pubsecd]
url = "$(pubsec_toml_escape "$api_url")"
EOF
    if [ -n "$push_token" ]; then
        printf 'push_token = "%s"\n' "$(pubsec_toml_escape "$push_token")"
    fi
    if [ -n "$read_token" ]; then
        printf 'read_token = "%s"\n' "$(pubsec_toml_escape "$read_token")"
    fi
    cat <<'EOF'
timeout_secs = 20

# ---------------------------------------------------------------- push
# Follow the fail2ban log and report bans as observations.
[push]
log = "/var/log/fail2ban.log"
state_file = "/var/lib/pubsec-fail2ban/push.state"
batch_interval_secs = 30
poll_interval_ms = 1000
# Never report the jail fed by "pull", otherwise bans imported from peers are
# re-published as your own sightings (feedback loop).
ignore_jails = ["pubsecd-ban"]
report_restored = false
max_queue = 10000
EOF

    for jail in $integrations; do
        map=$(pubsec_jail_map "$jail")
        behavior=${map%% *}
        rest=${map#* }
        port=${rest%% *}
        service=${rest##* }
        printf '\n[push.jails.%s]\nbehavior = "%s"\n' "$jail" "$behavior"
        if [ "$port" != "-" ]; then
            printf 'port = %s\n' "$port"
        fi
        if [ "$service" != "-" ]; then
            printf 'service = "%s"\n' "$service"
        fi
    done

    if [ "$ban_active" = true ]; then
        cat <<'EOF'

# ---------------------------------------------------------------- pull
# Write active IPs to a file that the pubsecd-ban jail follows.
[pull]
interval_secs = 300
# The jail's bantime must exceed refresh_secs + interval_secs.
refresh_secs = 1800

[[pull.output]]
EOF
        printf 'path = "%s"\n' "$PUBSEC_BAN_LOG"
        cat <<'EOF'
# Empty = all behaviours.
behaviors = []
types = ["ipv4-addr", "ipv6-addr"]
max_size_bytes = 10485760
EOF
    fi
} >"$new"

ucfr pubsec-fail2ban /etc/pubsec-fail2ban/config.toml
ucf --three-way --debconf-ok "$new" /etc/pubsec-fail2ban/config.toml
rm -f "$new"
chown root:pubsec-fail2ban /etc/pubsec-fail2ban/config.toml
chmod 0640 /etc/pubsec-fail2ban/config.toml

if ! pubsec-fail2ban --config /etc/pubsec-fail2ban/config.toml check >/dev/null 2>&1; then
    cat >&2 <<'EOF'
pubsec-fail2ban: the configuration is not usable yet (most likely the API
tokens are still missing). Edit /etc/pubsec-fail2ban/config.toml or run
"dpkg-reconfigure pubsec-fail2ban", then start pubsec-fail2ban.service.
EOF
fi

jails=$integrations
if [ "$ban_active" = true ]; then
    jails="$jails pubsecd-ban"
    # fail2ban aborts its configuration when a jail's logpath is missing, and
    # the file is only written by the first `pull` run, so create it empty.
    if [ ! -e "$PUBSEC_BAN_LOG" ]; then
        install -m 0640 -o pubsec-fail2ban -g adm /dev/null "$PUBSEC_BAN_LOG"
    fi
fi
for jail in $jails; do
    tpl=/usr/share/pubsec-fail2ban/jail.d/$jail.local
    dst=/etc/fail2ban/jail.d/$jail.local
    if [ -f "$tpl" ] && [ ! -e "$dst" ]; then
        install -m 0644 "$tpl" "$dst"
    fi
done

# Keep the tokens out of the debconf database, but leave the questions
# registered so dpkg-reconfigure can ask for them again.
db_set pubsec-fail2ban/push-token ""
db_set pubsec-fail2ban/read-token ""

if [ -d /run/systemd/system ] && systemctl is-enabled fail2ban.service >/dev/null 2>&1; then
    deb-systemd-invoke try-reload-or-restart fail2ban.service >/dev/null || true
fi
