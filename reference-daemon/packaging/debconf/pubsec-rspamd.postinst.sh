# Rendered into the postinst of pubsec-rspamd, inside the "configure" branch.
# build-deb.sh prepends the shared definitions.

pubsec_escape() {
    printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

# pubsec_toml_read TABLE KEY: reads a credential from the installed
# configuration. Placeholders of the former example configuration are not
# credentials.
pubsec_toml_read() {
    [ -f "$PUBSEC_CONFIG" ] || return 0
    v=$(pubsec_toml_get "$PUBSEC_CONFIG" "$1" "$2")
    case "$v" in
        *change-me*) ;;
        *) printf '%s' "$v" ;;
    esac
}

# pubsec_rspamd_secret FILE: prints the `secret` set in an Rspamd config file.
pubsec_rspamd_secret() {
    [ -f "$1" ] || return 0
    sed -n 's/^[[:space:]]*secret[[:space:]]*=[[:space:]]*"\(.*\)"[[:space:]]*;\{0,1\}[[:space:]]*$/\1/p' \
        "$1" | head -n 1 | pubsec_unescape
}

# Up to 2026.11.9 config.toml was a conffile. dpkg-maintscript-helper
# rm_conffile has moved a modified one to .dpkg-bak; put it back so that ucf
# below treats it as the admin's version and keeps it (or asks) instead of
# replacing it with a configuration generated from defaults. The config script
# has already read the answers from it.
if [ ! -e "$PUBSEC_CONFIG" ] && [ -f "$PUBSEC_CONFIG.dpkg-bak" ]; then
    mv "$PUBSEC_CONFIG.dpkg-bak" "$PUBSEC_CONFIG"
fi

# Prints a comma separated, quoted TOML array body from a list separated by
# spaces or commas.
pubsec_toml_list() {
    out=
    set -f
    for item in $(printf '%s' "$1" | tr ',' ' '); do
        out="${out:+$out, }\"$(pubsec_escape "$item")\""
    done
    set +f
    printf '%s' "$out"
}

db_get pubsec-rspamd/api-url
api_url=$RET
db_get pubsec-rspamd/push-token
push_token=$RET
db_get pubsec-rspamd/read-token
read_token=$RET
db_get pubsec-rspamd/report
report=$RET
db_get pubsec-rspamd/report-domains
report_domains=$RET
db_get pubsec-rspamd/ignore-networks
ignore_networks=$RET
db_get pubsec-rspamd/own-domains
own_domains=$RET
db_get pubsec-rspamd/use-maps
use_maps=$RET

# The tokens are cleared from the debconf database once written, so on a plain
# upgrade the answers are empty. Carry the installed values over, otherwise
# every upgrade would regenerate the configuration without credentials.
[ -n "$push_token" ] || push_token=$(pubsec_toml_read pubsecd push_token)
[ -n "$read_token" ] || read_token=$(pubsec_toml_read pubsecd read_token)

# The report secret of the generated configuration: the installed one, else
# one the admin has given the plugin by hand, else the one the package wrote
# before, else a new one.
secret=$(pubsec_toml_read ingest report_secret)
for f in /etc/rspamd/override.d/pubsec.conf /etc/rspamd/local.d/pubsec.conf \
    "$PUBSEC_RSPAMD_SECRET"; do
    [ -z "$secret" ] || break
    secret=$(pubsec_rspamd_secret "$f")
done
if [ -z "$secret" ]; then
    secret=$(od -An -tx1 -N32 /dev/urandom | tr -d ' \n')
fi

install -d -m 0750 -o root -g pubsec-rspamd /etc/pubsec-rspamd

new=$(mktemp)
chmod 0640 "$new"

# Heredocs and printf throughout: the echo of dash expands backslash escapes,
# which would undo the quoting of the token values.
{
    cat <<EOF
# Generated by the pubsec-rspamd package. Run "dpkg-reconfigure pubsec-rspamd"
# to change the answers given at install time; hand edits are preserved on
# upgrade.

[pubsecd]
url = "$(pubsec_escape "$api_url")"
EOF
    if [ -n "$push_token" ]; then
        printf 'push_token = "%s"\n' "$(pubsec_escape "$push_token")"
    fi
    if [ -n "$read_token" ]; then
        printf 'read_token = "%s"\n' "$(pubsec_escape "$read_token")"
    fi
    cat <<'EOF'
timeout_secs = 20

[server]
# Endpoint for the Lua plugin (/v1/report) and multimap (/maps/<name>). The
# URLs in /etc/rspamd/modules.local.d/pubsec.conf and
# /etc/rspamd/local.d/pubsec_multimap.inc point here. Keep it on loopback: the
# maps contain TLP-restricted data.
bind = "127.0.0.1:11380"
EOF

    if [ "$report" = true ]; then
        cat <<'EOF'

# ---------------------------------------------------------------- ingest
# Turn Rspamd scan results into observations of the sending IP and,
# optionally, the envelope-from domain.
[ingest]
# Copied to /etc/rspamd/local.d/pubsec_secret.inc for the Rspamd plugin when
# the package is configured. Run "dpkg-reconfigure pubsec-rspamd" after
# changing it.
EOF
        printf 'report_secret = "%s"\n' "$(pubsec_escape "$secret")"
        cat <<'EOF'
# A message is bad if its score minus the score of ignore_symbols reaches
# this. The plugin's min_score must not be higher.
min_score = 10.0
# Report an IP after this many bad messages within window_secs ...
min_messages = 3
window_secs = 3600
# ... and at most once per report_interval_secs while it keeps sending.
report_interval_secs = 3600
ipv6_prefix = 64
behavior = "smtp-spam"
service = "smtp"
port = 25
tlp = "green"
# The symbols of the multimap rules fed by [maps] must be listed here,
# otherwise IPs imported from peers are re-published as your own Sightings.
ignore_symbols = ["PUBSEC_*"]
# Never report these senders, e.g. own relays, backup MX, forwarders.
EOF
        printf 'ignore_networks = [%s]\n' "$(pubsec_toml_list "$ignore_networks")"
        cat <<'EOF'
ignore_authenticated = true
max_tracked = 100000
batch_interval_secs = 30
max_queue = 10000
EOF
        if [ "$report_domains" = true ]; then
            cat <<'EOF'

# Report the envelope-from (SMTP MAIL FROM) domains of bad messages.
[ingest.envelope_from]
behavior = "smtp-spam"
tlp = "green"
min_messages = 3
min_senders = 1
window_secs = 86400
report_interval_secs = 86400
# The envelope sender is forged easily. Count a message only if SPF
# authorised the sending IP for the domain.
require_symbols = ["R_SPF_ALLOW"]
skip_symbols = ["FREEMAIL_ENVFROM", "DISPOSABLE_ENVFROM"]
# Own domains and the bounce domains of mail service providers whose SPF
# passes for all their customers. Subdomains are covered as well.
ignore_domains = [
EOF
            set -f
            for domain in $PUBSEC_PROVIDER_DOMAINS $(printf '%s' "$own_domains" | tr ',' ' '); do
                printf '  "%s",\n' "$(pubsec_escape "$domain")"
            done
            set +f
            echo ']'
        fi
    fi

    if [ "$use_maps" = true ]; then
        cat <<'EOF'

# ---------------------------------------------------------------- maps
# Serve the active list as multimap files for the rules in
# /etc/rspamd/local.d/pubsec_multimap.inc.
[maps]
interval_secs = 60

# Sending IPs of any behaviour -> PUBSEC_BAD_IP.
[[maps.map]]
name = "ip"
kind = "ip"
behaviors = []
include_flagged = false

# Hosts of URLs in the message -> PUBSEC_BAD_URL.
[[maps.map]]
name = "url-domains"
kind = "domain"
behaviors = ["phishing", "malware-hosting", "command-and-control"]

# Envelope and header From domains -> PUBSEC_BAD_FROM, PUBSEC_BAD_HEADER_FROM.
[[maps.map]]
name = "sender-domains"
kind = "domain"
behaviors = ["smtp-spam"]
EOF
    fi
} >"$new"

ucfr pubsec-rspamd "$PUBSEC_CONFIG"
ucf --three-way --debconf-ok "$new" "$PUBSEC_CONFIG"
rm -f "$new"
chown root:pubsec-rspamd "$PUBSEC_CONFIG"
chmod 0640 "$PUBSEC_CONFIG"

# From here on the configuration as installed counts, not the answers: the
# admin may have kept a modified version in ucf. The Rspamd side is only
# activated while pubsec-rspamd can run, otherwise Rspamd would send every
# report to, and poll the maps from, a service that is not there.
usable=
reporting=
maps=
if pubsec-rspamd --config "$PUBSEC_CONFIG" check >/dev/null 2>&1; then
    usable=1
    if pubsec_toml_has "$PUBSEC_CONFIG" ingest; then
        reporting=1
    fi
    if pubsec_toml_has "$PUBSEC_CONFIG" maps; then
        maps=1
    fi
    # Read by the systemd section of the postinst: start the enabled unit.
    pubsec_start_units=1
else
    cat >&2 <<'EOF'
pubsec-rspamd: the configuration is not usable yet (most likely the API
tokens are still missing), so Rspamd is not set up to use it. Run
"dpkg-reconfigure pubsec-rspamd", or edit /etc/pubsec-rspamd/config.toml and
run "dpkg-reconfigure pubsec-rspamd" afterwards.
EOF
fi

# The report secret for the Lua plugin, kept in sync with the installed
# configuration. An empty secret disables the plugin.
final_secret=
if [ -n "$reporting" ]; then
    final_secret=$(pubsec_toml_get "$PUBSEC_CONFIG" ingest report_secret)
fi
rspamd_group=
for g in _rspamd rspamd; do
    if getent group "$g" >/dev/null; then
        rspamd_group=$g
        break
    fi
done
install -d -m 0755 /etc/rspamd/local.d
new=$(mktemp /etc/rspamd/local.d/.pubsec_secret.XXXXXX)
{
    cat <<'EOF'
# Generated by the pubsec-rspamd package from ingest.report_secret in
# /etc/pubsec-rspamd/config.toml whenever the package is configured; do not
# edit. Included by /etc/rspamd/modules.local.d/pubsec.conf.
EOF
    printf 'secret = "%s";\n' "$(pubsec_escape "$final_secret")"
} >"$new"
if [ -n "$rspamd_group" ]; then
    chown "root:$rspamd_group" "$new"
    chmod 0640 "$new"
else
    chmod 0644 "$new"
fi
mv -f "$new" "$PUBSEC_RSPAMD_SECRET"

# A secret set by hand in local.d or override.d takes precedence.
for f in /etc/rspamd/local.d/pubsec.conf /etc/rspamd/override.d/pubsec.conf; do
    own=$(pubsec_rspamd_secret "$f")
    if [ -n "$reporting" ] && [ -n "$own" ] && [ "$own" != "$final_secret" ]; then
        cat >&2 <<EOF
pubsec-rspamd: $f sets a secret that differs from
ingest.report_secret in $PUBSEC_CONFIG. Remove it from $f,
otherwise pubsec-rspamd rejects the reports of Rspamd.
EOF
    fi
done

if [ -n "$maps" ]; then
    if [ ! -e "$PUBSEC_MULTIMAP" ]; then
        pubsec_multimap_stub >"$PUBSEC_MULTIMAP"
        chmod 0644 "$PUBSEC_MULTIMAP"
    fi
elif pubsec_multimap_is_stub "$PUBSEC_MULTIMAP"; then
    rm -f "$PUBSEC_MULTIMAP"
fi

# Keep the tokens out of the debconf database, but leave the questions
# registered so dpkg-reconfigure can ask for them again.
db_set pubsec-rspamd/push-token ""
db_set pubsec-rspamd/read-token ""

if [ -d /run/systemd/system ] && systemctl is-enabled rspamd.service >/dev/null 2>&1; then
    deb-systemd-invoke try-reload-or-restart rspamd.service >/dev/null || true
fi
